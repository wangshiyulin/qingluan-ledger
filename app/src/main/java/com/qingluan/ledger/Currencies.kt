    private val byCode = all.associateBy { it.code }

    fun get(code: String): CurrencyUnit = requireNotNull(byCode[code]) { "不支持的币种：$code" }

    fun contains(code: String): Boolean = code in byCode

    private fun unit(code: String, fallbackName: String, digits: Int): CurrencyUnit {
        val name =
            try {
                java.util.Currency.getInstance(code)
                    .getDisplayName(Locale.getDefault())
                    .takeUnless { it == code || it.isBlank() } ?: fallbackName
            } catch (_: IllegalArgumentException) {
                fallbackName
            }
        return CurrencyUnit(code, name, digits)
    }
